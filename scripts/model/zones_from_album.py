# сквозной проход: полоса по X, не занятая ни одним контуром
bands = sorted((r['minp'][0], r['maxp'][0]) for r in rows if r['maxp'][1] < -6)
merged = []
for a, b in bands:
    if merged and a <= merged[-1][1] + 0.01:
        merged[-1][1] = max(merged[-1][1], b)
    else:
        merged.append([a, b])
gaps = [(m1[1], m2[0]) for m1, m2 in zip(merged, merged[1:]) if m2[0] - m1[1] > 2]
aisle = round(sum(gaps[0]) / 2, 2) if gaps else 25.21
print('проходы шире 2 м:', [(round(a, 2), round(b, 2)) for a, b in gaps], '-> ось прохода', aisle)

